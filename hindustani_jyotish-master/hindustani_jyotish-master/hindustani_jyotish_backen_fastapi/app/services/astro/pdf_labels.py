def title(en_title: str, lang: str | None) -> str:
    """Localized service title; the English title itself if not catalogued."""
    full = normalize_lang(lang) if lang else "english"
    entry = _TITLES.get(en_title)
    return entry.get(full, en_title) if entry else en_title


def heading(key: str, lang: str | None, *, fallback: str) -> str:
    """Localized section heading for a data key; `fallback` (a humanized English
    label) when the key isn't catalogued so a new section still renders."""
    full = normalize_lang(lang) if lang else "english"
    entry = _LABELS.get(str(key).strip().lower())
    return entry.get(full, fallback) if entry else fallback
