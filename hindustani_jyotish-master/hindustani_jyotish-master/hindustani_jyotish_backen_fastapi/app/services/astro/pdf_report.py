def _num(v: Any, dp: int = 0) -> str:
    if isinstance(v, bool) or v is None:
        return ""
    if isinstance(v, (int, float)):
        return f"{v:.{dp}f}" if dp else f"{int(round(v))}"
    return _e(str(v))


def _t(v: Any) -> str:
    return _e("" if v is None else str(v))


def _planet_name(name: str, full: str) -> str:
    loc = _cat(f"planet.{name.lower()}", full)
    return name if loc.startswith("planet.") else loc


def _north_indian_svg(chart: dict) -> str:
    """Inline SVG North-Indian diamond from numeric indices (localization-safe)."""
    size = 340
    half = size / 2
    q = size / 4
    lagna_idx = chart.get("lagna", {}).get("sign_idx")
    if not isinstance(lagna_idx, int):
        lagna_idx = chart.get("ascendant_sign_idx")
    if not isinstance(lagna_idx, int):
        lagna_idx = 0
    anchors = {
        1: (half, q), 2: (q, q * 0.55), 3: (q * 0.55, q), 4: (q, half),
        5: (q * 0.55, size - q), 6: (q, size - q * 0.55), 7: (half, size - q),
        8: (size - q, size - q * 0.55), 9: (size - q * 0.55, size - q),
        10: (size - q, half), 11: (size - q * 0.55, q), 12: (size - q, q * 0.55),
    }
    abbr = {"Sun": "Su", "Moon": "Mo", "Mars": "Ma", "Mercury": "Me",
            "Jupiter": "Ju", "Venus": "Ve", "Saturn": "Sa", "Rahu": "Ra", "Ketu": "Ke"}
    by_house: dict[int, list[str]] = {}
    for nm, p in (chart.get("planets") or {}).items():
        if not isinstance(p, dict):
            continue
        si = p.get("sign_idx")
        if not isinstance(si, int):
            continue
        h = (si - lagna_idx) % 12 + 1
        by_house.setdefault(h, []).append(abbr.get(nm, nm[:2]) + ("*" if p.get("vakri") else ""))
    lines = [
        f'<rect x="0" y="0" width="{size}" height="{size}" fill="#FBF6EE" stroke="{_INDIGO}" stroke-width="2"/>',
        f'<line x1="0" y1="0" x2="{size}" y2="{size}" stroke="{_INDIGO}"/>',
        f'<line x1="{size}" y1="0" x2="0" y2="{size}" stroke="{_INDIGO}"/>',
        f'<line x1="0" y1="{half}" x2="{half}" y2="0" stroke="{_INDIGO}"/>',
        f'<line x1="{half}" y1="0" x2="{size}" y2="{half}" stroke="{_INDIGO}"/>',
        f'<line x1="{size}" y1="{half}" x2="{half}" y2="{size}" stroke="{_INDIGO}"/>',
        f'<line x1="{half}" y1="{size}" x2="0" y2="{half}" stroke="{_INDIGO}"/>',
    ]
    for house, (x, y) in anchors.items():
        sign_no = (lagna_idx + house - 1) % 12 + 1
        lines.append(f'<text x="{x}" y="{y - 8}" font-size="10" fill="{_COPPER}" '
                     f'text-anchor="middle">{sign_no}</text>')
        occ = " ".join(by_house.get(house, []))
        if occ:
            lines.append(f'<text x="{x}" y="{y + 10}" font-size="11" fill="{_INDIGO}" '
                         f'text-anchor="middle" font-weight="bold">{_e(occ)}</text>')
    return f'<svg viewBox="0 0 {size} {size}" width="360" height="360">{"".join(lines)}</svg>'


def build_kundli_report_pdf(
    data: dict,
    *,
    name: str | None,
    dob: date,
    birth_time: time | None,
    birth_place: str | None,
    lang: str | None,
) -> bytes:
    """Render the localized full-analysis bundle to a multi-page PDF via
    WeasyPrint. Raises if WeasyPrint/its system libs are unavailable (caller
    falls back to the reportlab builder)."""
    from weasyprint import HTML  # imported lazily so absence → caller fallback

    full = normalize_lang(lang) if lang else "english"
    L = {**_L["english"], **_L.get(full, {})}
    S = {**_SL["english"], **_SL.get(full, {})}

    chart = data.get("chart") if isinstance(data.get("chart"), dict) else {}
    numerology = data.get("numerology") if isinstance(data.get("numerology"), dict) else {}

    def h2(txt: str) -> str:
        return f'<h2>{_t(txt)}</h2>'

    def table(headers: list[str], rows: list[list[str]]) -> str:
        if not rows:
            return ""
        head = "".join(f"<th>{_t(h)}</th>" for h in headers)
        body = "".join(
            "<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows
        )
        return f'<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>'

    sections: list[str] = []

