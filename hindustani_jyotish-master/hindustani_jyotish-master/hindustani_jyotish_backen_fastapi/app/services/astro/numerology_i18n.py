def _norm(lang) -> str:
    if not lang or not isinstance(lang, str):
        return "en"
    key = lang.split(",")[0].split(";")[0].strip().lower().replace("-", "_")
    return _ALIASES.get(key, _ALIASES.get(key.split("_")[0], "en"))


def tr(text: str, lang) -> str:
    code = _norm(lang)
    if code == "en" or not isinstance(text, str):
        return text
    return _MEANINGS_I18N.get(text, {}).get(code, text)
