def _norm(lang) -> str:
    if not lang or not isinstance(lang, str):
        return "en"
    key = lang.split(",")[0].split(";")[0].strip().lower().replace("-", "_")
    return _ALIASES.get(key, _ALIASES.get(key.split("_")[0], "en"))


def tr(text: str, lang) -> str:
    code = _norm(lang)
    if code == "en" or not isinstance(text, str):
        return text
    return _PHRASES.get(text, {}).get(code, text)


def overall_line(energy: str, color: str, lang) -> str:
    code = _norm(lang)
    tmpl = _OVERALL.get(code)
    if not tmpl:
        return f"Overall your energy is {energy} — favour {color}."
    return tmpl.format(energy=energy, color=color)
